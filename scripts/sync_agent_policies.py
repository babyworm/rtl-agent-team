#!/usr/bin/env python3
"""Inline only the declared policy fragments; --check reports generated drift."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '<!-- RAT_POLICIES_BEGIN: generated by scripts/sync_agent_policies.py -->'
END = '<!-- RAT_POLICIES_END -->'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'plugin_docs/agent-lib/policy-manifest.json').read_text())
    changed = []
    for name, policies in manifest.items():
        path = ROOT / 'agents' / (name + '.md')
        original = path.read_text()
        content = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\s*', '', original, flags=re.S).rstrip()
        block = '\n\n'.join((ROOT / 'plugin_docs/agent-lib/policies' / (policy + '.md')).read_text().strip() for policy in policies)
        updated = content + '\n\n' + BEGIN + '\n' + block + '\n' + END + '\n'
        if updated != original:
            changed.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(updated)
    if args.check and changed:
        print('Policy drift: ' + ', '.join(changed))
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
